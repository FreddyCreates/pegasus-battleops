"""
Bot Layer — Nuntii  ⊡

Small, focused task bots that execute narrow, repeatable operations.
Unlike full agents, bots are stateless, single-purpose, and fast.

Charter Reference:
  "Small task bots that execute narrow actions:
   email bot, PDF bot, estimate bot, quote bot,
   punch bot, field-note bot, schedule bot"

Each bot:
- Has a single, well-defined purpose
- Takes structured input, returns structured output
- Is stateless (no memory between invocations)
- Can be invoked by any agent or the orchestrator

Glyph: ⊡ — task bot
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Callable, Awaitable

from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Models
# ---------------------------------------------------------------------------

class BotStatus(str, Enum):
    """Bot operational status."""
    ACTIVE = "active"
    DISABLED = "disabled"
    DEPRECATED = "deprecated"


class Bot(BaseModel):
    """Definition of a task bot."""
    bot_id: str
    name: str
    glyph: str = "⊡"
    description: str
    
    # What it does
    input_schema: dict[str, Any] = Field(default_factory=dict)
    output_schema: dict[str, Any] = Field(default_factory=dict)
    
    # Metadata
    category: str = "general"
    version: str = "1.0.0"
    status: BotStatus = BotStatus.ACTIVE
    
    # Performance
    avg_latency_ms: float = 0.0
    invocation_count: int = 0
    error_count: int = 0


class BotResult(BaseModel):
    """Result from invoking a bot."""
    bot_id: str
    bot_name: str
    success: bool
    output: dict[str, Any] = Field(default_factory=dict)
    error: str | None = None
    duration_ms: float = 0.0
    invoked_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


