# Type for bot handlers
BotHandler = Callable[[dict[str, Any]], Awaitable[dict[str, Any]]]


class BotRegistry:
    """Registry of all available task bots."""

    def __init__(self):
        self._bots: dict[str, Bot] = {}
        self._handlers: dict[str, BotHandler] = {}
        self._register_defaults()

    def _register_defaults(self) -> None:
        """Register all built-in bots."""
        defaults = [
            ("email", "⊡✉", "Email Bot", "Formats and prepares emails for sending", "communication", _email_bot_handler),
            ("pdf", "⊡📄", "PDF Bot", "Prepares content for PDF generation", "documents", _pdf_bot_handler),
            ("estimate", "⊡💰", "Estimate Bot", "Quick calculation helper for estimates", "estimating", _estimate_bot_handler),
            ("quote", "⊡📋", "Quote Bot", "Normalizes and compares vendor quotes", "estimating", _quote_bot_handler),
            ("punch", "⊡✓", "Punch Bot", "Creates and formats punch list items", "field", _punch_bot_handler),
            ("field_note", "⊡📝", "Field Note Bot", "Structures raw field notes into actionable data", "field", _field_note_bot_handler),
            ("schedule", "⊡📅", "Schedule Bot", "Calculates scheduling and timeline logic", "workflow", _schedule_bot_handler),
        ]

        for bot_id, glyph, name, desc, category, handler in defaults:
            self._bots[bot_id] = Bot(
                bot_id=bot_id,
                name=name,
                glyph=glyph,
                description=desc,
                category=category,
            )
            self._handlers[bot_id] = handler

    def register(self, bot_id: str, bot: Bot, handler: BotHandler) -> None:
        """Register a custom bot."""
        self._bots[bot_id] = bot
        self._handlers[bot_id] = handler

    def get(self, bot_id: str) -> Bot | None:
        """Get bot definition by ID."""
        return self._bots.get(bot_id)

    def list_all(self) -> list[Bot]:
        """List all registered bots."""
        return [b for b in self._bots.values() if b.status == BotStatus.ACTIVE]

    def list_by_category(self, category: str) -> list[Bot]:
        """List bots in a specific category."""
        return [
            b for b in self._bots.values()
            if b.category == category and b.status == BotStatus.ACTIVE
        ]

    async def invoke(self, bot_id: str, input_data: dict[str, Any]) -> BotResult:
        """Invoke a bot with input data."""
        import time

        bot = self._bots.get(bot_id)
        if not bot:
            return BotResult(
                bot_id=bot_id,
                bot_name="unknown",
                success=False,
                error=f"Bot '{bot_id}' not found",
            )

        if bot.status != BotStatus.ACTIVE:
            return BotResult(
                bot_id=bot_id,
                bot_name=bot.name,
                success=False,
                error=f"Bot '{bot_id}' is {bot.status.value}",
            )

        handler = self._handlers.get(bot_id)
        if not handler:
            return BotResult(
                bot_id=bot_id,
                bot_name=bot.name,
                success=False,
                error=f"No handler registered for bot '{bot_id}'",
            )

        start = time.perf_counter()
        try:
            output = await handler(input_data)
            duration_ms = (time.perf_counter() - start) * 1000

            # Update stats
            bot.invocation_count += 1
            bot.avg_latency_ms = (
                (bot.avg_latency_ms * (bot.invocation_count - 1) + duration_ms)
                / bot.invocation_count
            )

            return BotResult(
                bot_id=bot_id,
                bot_name=bot.name,
                success=True,
                output=output,
                duration_ms=duration_ms,
            )

        except Exception as e:
            duration_ms = (time.perf_counter() - start) * 1000
            bot.error_count += 1
            bot.invocation_count += 1

            return BotResult(
                bot_id=bot_id,
                bot_name=bot.name,
                success=False,
                error=str(e),
                duration_ms=duration_ms,
            )


# ---------------------------------------------------------------------------
# Global Instance & Convenience Functions
# ---------------------------------------------------------------------------

_global_registry: BotRegistry | None = None


def _get_registry() -> BotRegistry:
    global _global_registry
    if _global_registry is None:
        _global_registry = BotRegistry()
    return _global_registry


def get_bot(bot_id: str) -> Bot | None:
    """Get a bot by ID."""
    return _get_registry().get(bot_id)


def list_bots(category: str | None = None) -> list[Bot]:
    """List all bots, optionally filtered by category."""
    if category:
        return _get_registry().list_by_category(category)
    return _get_registry().list_all()


async def invoke_bot(bot_id: str, input_data: dict[str, Any]) -> BotResult:
    """Invoke a bot with input data."""
    return await _get_registry().invoke(bot_id, input_data)
