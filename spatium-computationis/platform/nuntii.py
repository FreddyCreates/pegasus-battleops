async def _email_bot_handler(input_data: dict[str, Any]) -> dict[str, Any]:
    """
    Email Bot — Formats and prepares emails for sending.
    
    Input: {to, subject, body, template?, attachments?}
    Output: {formatted_email, ready_to_send}
    """
    to = input_data.get("to", "")
    subject = input_data.get("subject", "")
    body = input_data.get("body", "")
    template = input_data.get("template", "default")
    
    # Format based on template
    if template == "bid_submission":
        formatted_body = f"Dear Team,\n\nPlease find attached our bid submission.\n\n{body}\n\nBest regards,\nSpatium Computationis"
    elif template == "field_update":
        formatted_body = f"Field Update:\n\n{body}\n\n— Sent from Spatium Computationis Field System"
    elif template == "rfi":
        formatted_body = f"REQUEST FOR INFORMATION\n\n{body}\n\nPlease respond at your earliest convenience."
    else:
        formatted_body = body

    return {
        "formatted_email": {
            "to": to,
            "subject": subject,
            "body": formatted_body,
            "template_used": template,
        },
        "ready_to_send": bool(to and subject and formatted_body),
        "character_count": len(formatted_body),
    }


async def _pdf_bot_handler(input_data: dict[str, Any]) -> dict[str, Any]:
    """
    PDF Bot — Prepares content for PDF generation.
    
    Input: {title, sections, document_type, project_id?}
    Output: {pdf_spec, page_count_estimate, ready}
    """
    title = input_data.get("title", "Untitled Document")
    sections = input_data.get("sections", [])
    document_type = input_data.get("document_type", "general")

    # Build PDF specification
    pdf_spec = {
        "title": title,
        "document_type": document_type,
        "header": {
            "logo": "spatium_computationis_logo",
            "title": title,
            "date": datetime.now(timezone.utc).strftime("%Y-%m-%d"),
        },
        "sections": sections,
        "footer": {
            "text": "Generated by Spatium Computationis ⌬",
            "page_numbers": True,
        },
    }

    # Estimate page count
    total_chars = sum(len(str(s.get("content", ""))) for s in sections)
    page_estimate = max(1, total_chars // 3000)

    return {
        "pdf_spec": pdf_spec,
        "page_count_estimate": page_estimate,
        "section_count": len(sections),
        "ready": len(sections) > 0,
    }


async def _estimate_bot_handler(input_data: dict[str, Any]) -> dict[str, Any]:
    """
    Estimate Bot — Quick calculation helper for estimates.
    
    Input: {items: [{description, quantity, unit_price}], markup_percent?, tax_percent?}
    Output: {subtotal, markup, tax, total, line_items}
    """
    items = input_data.get("items", [])
    markup_percent = input_data.get("markup_percent", 0.0)
    tax_percent = input_data.get("tax_percent", 0.0)

    line_items = []
    subtotal = 0.0

    for item in items:
        qty = item.get("quantity", 1)
        unit_price = item.get("unit_price", 0.0)
        line_total = qty * unit_price
        subtotal += line_total
        line_items.append({
            "description": item.get("description", ""),
            "quantity": qty,
            "unit_price": unit_price,
            "line_total": line_total,
        })

    markup = subtotal * (markup_percent / 100.0)
    after_markup = subtotal + markup
    tax = after_markup * (tax_percent / 100.0)
    total = after_markup + tax

    return {
        "line_items": line_items,
        "subtotal": round(subtotal, 2),
        "markup": round(markup, 2),
        "markup_percent": markup_percent,
        "tax": round(tax, 2),
        "tax_percent": tax_percent,
        "total": round(total, 2),
        "item_count": len(line_items),
    }


async def _quote_bot_handler(input_data: dict[str, Any]) -> dict[str, Any]:
    """
    Quote Bot — Normalizes and compares vendor quotes.
    
    Input: {quotes: [{vendor, items: [{description, price}], freight?, lead_time?}]}
    Output: {comparison, lowest_total, recommended}
    """
    quotes = input_data.get("quotes", [])

    comparison = []
    for quote in quotes:
        vendor = quote.get("vendor", "Unknown")
        items = quote.get("items", [])
        freight = quote.get("freight", 0.0)
        lead_time = quote.get("lead_time", "Unknown")

        items_total = sum(item.get("price", 0.0) for item in items)
        total = items_total + freight

        comparison.append({
            "vendor": vendor,
            "items_total": round(items_total, 2),
            "freight": round(freight, 2),
            "total": round(total, 2),
            "lead_time": lead_time,
            "item_count": len(items),
        })

    # Sort by total
    comparison.sort(key=lambda x: x["total"])
    
    recommended = comparison[0]["vendor"] if comparison else None

    return {
        "comparison": comparison,
        "quote_count": len(comparison),
        "lowest_total": comparison[0]["total"] if comparison else 0.0,
        "highest_total": comparison[-1]["total"] if comparison else 0.0,
        "recommended": recommended,
    }


async def _punch_bot_handler(input_data: dict[str, Any]) -> dict[str, Any]:
    """
    Punch Bot — Creates and formats punch list items.
    
    Input: {items: [{room, description, responsible?, photo_ref?}], project_id?}
    Output: {formatted_list, open_count, summary}
    """
    items = input_data.get("items", [])
    project_id = input_data.get("project_id")

    formatted_items = []
    for i, item in enumerate(items, 1):
        formatted_items.append({
            "item_number": i,
            "item_id": f"PI-{str(uuid.uuid4())[:8].upper()}",
            "room": item.get("room", "Unspecified"),
            "description": item.get("description", ""),
            "responsible_party": item.get("responsible", "TBD"),
            "photo_ref": item.get("photo_ref"),
            "status": "open",
            "created_at": datetime.now(timezone.utc).isoformat(),
        })

    # Group by room
    rooms = {}
    for item in formatted_items:
        room = item["room"]
        if room not in rooms:
            rooms[room] = []
        rooms[room].append(item)

    return {
        "project_id": project_id,
        "formatted_list": formatted_items,
        "by_room": rooms,
        "open_count": len(formatted_items),
        "room_count": len(rooms),
        "summary": f"{len(formatted_items)} punch items across {len(rooms)} rooms",
    }


async def _field_note_bot_handler(input_data: dict[str, Any]) -> dict[str, Any]:
    """
    Field Note Bot — Structures raw field notes into actionable data.
    
    Input: {raw_notes: str, worker?, location?, timestamp?}
    Output: {structured_note, action_items, issues_flagged}
    """
    raw_notes = input_data.get("raw_notes", "")
    worker = input_data.get("worker", "Unknown")
    location = input_data.get("location", "Unspecified")

    # Parse action items (lines starting with - or *)
    lines = raw_notes.strip().split("\n")
    action_items = []
    issues = []
    observations = []

    for line in lines:
        line = line.strip()
        if not line:
            continue
        lower = line.lower()
        if any(kw in lower for kw in ["issue", "problem", "broken", "damaged", "missing", "wrong"]):
            issues.append(line)
        elif line.startswith(("-", "*", "•")) or any(kw in lower for kw in ["need", "must", "should", "todo"]):
            action_items.append(line.lstrip("-*• "))
        else:
            observations.append(line)

    return {
        "structured_note": {
            "worker": worker,
            "location": location,
            "timestamp": input_data.get("timestamp", datetime.now(timezone.utc).isoformat()),
            "observations": observations,
            "action_items": action_items,
            "issues": issues,
        },
        "action_item_count": len(action_items),
        "issue_count": len(issues),
        "requires_attention": len(issues) > 0,
    }


async def _schedule_bot_handler(input_data: dict[str, Any]) -> dict[str, Any]:
    """
    Schedule Bot — Calculates scheduling and timeline logic.
    
    Input: {tasks: [{name, duration_hours, depends_on?}], start_date?, work_hours_per_day?}
    Output: {timeline, total_duration, critical_path, end_date}
    """
    tasks = input_data.get("tasks", [])
    start_date = input_data.get("start_date", datetime.now(timezone.utc).strftime("%Y-%m-%d"))
    work_hours = input_data.get("work_hours_per_day", 8)

    # Simple forward-pass scheduling
    task_map = {}
    timeline = []
    current_hour = 0

    for task in tasks:
        name = task.get("name", "")
        duration = task.get("duration_hours", 0)
        depends_on = task.get("depends_on", [])

        # Find earliest start (after all dependencies)
        earliest_start = 0
        for dep in depends_on:
            if dep in task_map:
                dep_end = task_map[dep]["end_hour"]
                earliest_start = max(earliest_start, dep_end)

        start_hour = max(current_hour, earliest_start)
        end_hour = start_hour + duration

        task_entry = {
            "name": name,
            "start_hour": start_hour,
            "end_hour": end_hour,
            "duration_hours": duration,
            "start_day": start_hour / work_hours,
            "end_day": end_hour / work_hours,
            "depends_on": depends_on,
        }
        task_map[name] = task_entry
        timeline.append(task_entry)

    total_hours = max((t["end_hour"] for t in timeline), default=0)
    total_days = total_hours / work_hours

    return {
        "timeline": timeline,
        "total_duration_hours": total_hours,
        "total_duration_days": round(total_days, 1),
        "work_hours_per_day": work_hours,
        "start_date": start_date,
        "task_count": len(timeline),
    }


